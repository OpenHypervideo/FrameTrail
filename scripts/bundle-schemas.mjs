/*
 * Writes src/_shared/frametrail-core/schema/FrameTrailSchemas.js: every schema in schemas/ in one script, so the player can validate data with FrameTrailSchema without fetching anything. Titles and descriptions are left out — they are most of the size and do not take part in validation. Run it after changing a schema:
 *
 *     node scripts/bundle-schemas.mjs
 *
 * tests/run-js.mjs fails while the file differs from what this writes.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SCHEMAS_DIR = path.join(ROOT, 'schemas');
export const OUTPUT      = path.join(ROOT, 'src', '_shared', 'frametrail-core', 'schema', 'FrameTrailSchemas.js');

// Where a keyword's value holds schemas (see KEYWORDS in FrameTrailSchema.js). Everywhere else a key named "title" or "description" is data: a property name, a const, a default.
const SUBSCHEMAS = {
    '$defs':                'map',
    'properties':           'map',
    'additionalProperties': 'schema',
    'items':                'schema',
    'oneOf':                'list'
};

function strip(schema) {

    if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) { return schema; }

    const out = {};

    for (const keyword of Object.keys(schema)) {
        const value = schema[keyword];
        if (keyword === 'title' || keyword === 'description') { continue; }
        switch (SUBSCHEMAS[keyword]) {
            case 'map':
                out[keyword] = {};
                for (const name of Object.keys(value)) { out[keyword][name] = strip(value[name]); }
                break;
            case 'schema':
                out[keyword] = strip(value);
                break;
            case 'list':
                out[keyword] = value.map(strip);
                break;
            default:
                out[keyword] = value;
        }
    }

    return out;

}

function schemaFiles(rel = '') {
    return fs.readdirSync(path.join(SCHEMAS_DIR, rel)).sort().flatMap((name) => {
        const file = rel ? rel + '/' + name : name;
        if (fs.statSync(path.join(SCHEMAS_DIR, file)).isDirectory()) { return schemaFiles(file); }
        return name.endsWith('.schema.json') ? [file] : [];
    });
}

/**
 * The contents of FrameTrailSchemas.js for the schemas in schemas/ now.
 * @return {String}
 */
export function bundleSchemas() {

    const schemas = schemaFiles().map((file) => strip(JSON.parse(fs.readFileSync(path.join(SCHEMAS_DIR, file), 'utf8'))));

    return '/*\n'
        + ' * The JSON Schemas of schemas/, without titles and descriptions, for FrameTrailSchema.create(): window.FrameTrailSchemas in the browser, module.exports under require().\n'
        + ' *\n'
        + ' * Generated by scripts/bundle-schemas.mjs. Do not edit; change the schemas and run it again.\n'
        + ' */\n'
        + '\n'
        + '(function(schemas) {\n'
        + '\n'
        + '    if (typeof window !== \'undefined\') {\n'
        + '        window.FrameTrailSchemas = schemas;\n'
        + '    }\n'
        + '    if (typeof module === \'object\' && module && module.exports) {\n'
        + '        module.exports = schemas;\n'
        + '    }\n'
        + '\n'
        + '})([\n'
        + schemas.map((schema) => JSON.stringify(schema)).join(',\n') + '\n'
        + ']);\n';

}


if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    fs.writeFileSync(OUTPUT, bundleSchemas());
    console.log('Wrote ' + path.relative(ROOT, OUTPUT));
}
